def fetch_web_content(url: str) -> Optional[str]:
    try:
        headers = {'User-Agent': USER_AGENT}
        response = requests.get(url, headers=headers, timeout=15)
        response.encoding = response.apparent_encoding
        
        soup = BeautifulSoup(response.text, 'html.parser')
        
        for script in soup(["script", "style", "nav", "footer", "header"]):
            script.decompose()
        
        text = soup.get_text()
        
        lines = (line.strip() for line in text.splitlines())
        chunks = (phrase.strip() for line in lines for phrase in line.split("  "))
        text = ' '.join(chunk for chunk in chunks if chunk)
        
        return text
    except requests.exceptions.Timeout:
        raise Exception(f"请求超时，请检查网络连接或稍后重试")
    except requests.exceptions.RequestException as e:
        raise Exception(f"请求失败: {str(e)}")
    except Exception as e:
        raise Exception(f"解析网页失败: {str(e)}")

def process_text(text: str, min_freq: int = 1) -> pd.DataFrame:
    words = jieba.lcut(text)
    
    chinese_pattern = re.compile(r'[\u4e00-\u9fa5]')
    
    filtered_words = [
        word for word in words
        if len(word) >= 2 and word not in STOP_WORDS and chinese_pattern.search(word)
    ]
    
    word_freq = Counter(filtered_words)
    word_freq = {word: freq for word, freq in word_freq.items() if freq >= min_freq}
    
    df = pd.DataFrame(list(word_freq.items()), columns=['词汇', '频率'])
    df = df.sort_values('频率', ascending=False).reset_index(drop=True)
    
    return df

def extract_keywords(text: str, top_n: int = 10) -> List[Tuple[str, float]]:
    keywords = jieba.analyse.extract_tags(text, topK=top_n, withWeight=True)
    return keywords